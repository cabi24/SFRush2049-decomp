def pure_normalizer(row):
    source = ROOT / row['generator']
    tree = ast.parse(source.read_text())
    definitions = [n for n in tree.body if isinstance(n, ast.FunctionDef)
                   and n.name in (row['normalizer'], 'require')]
    assignments = {target.id: n.value for n in tree.body if isinstance(n, ast.Assign)
                   for target in n.targets if isinstance(target, ast.Name)}
    namespace = {'json': json, 'copy': copy}
    safe = (ast.Constant, ast.Name, ast.List, ast.Tuple, ast.Set, ast.Dict,
            ast.BinOp, ast.Add, ast.Load)
    def bind(name):
        if name in namespace or name not in assignments:
            return
        value = assignments[name]
        assert all(isinstance(n, safe) for n in ast.walk(value)), name
        for node in ast.walk(value):
            if isinstance(node, ast.Name):
                bind(node.id)
        namespace[name] = eval(compile(ast.Expression(value), str(source), 'eval'), namespace)
    for function in definitions:
        for node in ast.walk(function):
            if isinstance(node, ast.Name) and node.id.isupper():
                bind(node.id)
    exec(compile(ast.Module(body=definitions, type_ignores=[]), str(source), 'exec'), namespace)
    return namespace[row['normalizer']]


def contains(value, path):
    try:
        for key in path:
            value = value[key]
        return True
    except (KeyError, IndexError):
        return False


def insert(value, path, replacement):
    result = copy.deepcopy(value)
    node = result
    for key in path[:-1]:
        if isinstance(node, dict):
            node = node.setdefault(key, {})
        else:
            node = node[key]
    node[path[-1]] = replacement
    return result


def leaves(value, path=()):
    if isinstance(value, dict) and value:
        for key, child in value.items():
            yield from leaves(child, path + (key,))
    elif isinstance(value, list) and value:
        for index, child in enumerate(value):
            yield from leaves(child, path + (index,))
    else:
        yield path


