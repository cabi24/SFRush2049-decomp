@pytest.mark.parametrize('row', PACKETS, ids=lambda r: r['generator'])
def test_legacy_provenance_is_not_proof(row):
    receipt = json.loads((ROOT / row['receipt']).read_text())
    normalize = pure_normalizer(row)
    expected = normalize(receipt)
    unchanged = copy.deepcopy(receipt)
    for item in row['removed']:
        changed = insert(receipt, item['path'], item['legacy_shape'])
        assert normalize(changed) == expected, item['path']
    assert receipt == unchanged


@pytest.mark.parametrize('row', PACKETS, ids=lambda r: r['generator'])
def test_every_retained_proof_field_rejects_mutation(row):
    receipt = json.loads((ROOT / row['receipt']).read_text())
    normalize = pure_normalizer(row)
    expected = normalize(receipt)
    for path in leaves(expected):
        changed = insert(receipt, path, 'deliberate proof drift')
        try:
            actual = normalize(changed)
        except (AssertionError, KeyError, ValueError, TypeError, AttributeError):
            continue
        assert actual != expected, path
    changed = copy.deepcopy(receipt)
    changed['unknown_proof_field'] = 'must stay bound'
    assert normalize(changed) != expected
