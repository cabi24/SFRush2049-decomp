#!/usr/bin/env python3
"""w23g: prove each libgcc-named boot helper is its ultralib ll.c/llcvt.c function.

For every row: the locked definition in src/rom (at --base, before the rename)
with the rename applied equals, token for token, the ultralib function's
definition (comments/whitespace ignored); and the ROM order of the 18 bodies
equals the definition order of ll.c then llcvt.c. Writes ll_renames.json."""
import json, re, subprocess, sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[4]
ULTRA = Path(sys.argv[1] if len(sys.argv) > 1 else REPO / "reference/repos/ultralib")
BASE = sys.argv[2] if len(sys.argv) > 2 else "HEAD"
ROWS = [  # (vram, old, new, ultralib file, rom TU)
    (0x8000D8F0, "__lshrdi3", "__ull_rshift", "ll.c", "lib_e4f0"),
    (0x8000D91C, "__umoddi3", "__ull_rem", "ll.c", "lib_e4f0"),
    (0x8000D958, "__udivdi3", "__ull_div", "ll.c", "lib_e4f0"),
    (0x8000D994, "__ashldi3", "__ll_lshift", "ll.c", "lib_e4f0"),
    (0x8000D9C0, "__umoddi3_alt", "__ll_rem", "ll.c", "lib_e4f0"),
    (0x8000D9FC, "__divdi3", "__ll_div", "ll.c", "lib_e4f0"),
    (0x8000DA58, "__muldi3", "__ll_mul", "ll.c", "lib_e4f0"),
    (0x8000DA88, "__qdivrem", "__ull_divremi", "ll.c", "lib_e4f0"),
    (0x8000DAE8, "__moddi3", "__ll_mod", "ll.c", "lib_e4f0"),
    (0x8000DB84, "__ashrdi3", "__ll_rshift", "ll.c", "lib_e4f0"),
    (0x800099F0, "__fixdfdi", "__d_to_ll", "llcvt.c", "lib_a5f0"),
    (0x80009A0C, "__fixsfdi", "__f_to_ll", "llcvt.c", "lib_a5f0"),
    (0x80009A28, "__fixunsdfdi", "__d_to_ull", "llcvt.c", "lib_a5f0"),
    (0x80009AC8, "__fixunssfdi", "__f_to_ull", "llcvt.c", "lib_a5f0"),
    (0x80009B64, "__floatdidf", "__ll_to_d", "llcvt.c", "lib_a5f0"),
    (0x80009B7C, "__floatdisf", "__ll_to_f", "llcvt.c", "lib_a5f0"),
    (0x80009B94, "__floatundidf", "__ull_to_d", "llcvt.c", "lib_a5f0"),
    (0x80009BC8, "__floatundisf", "__ull_to_f", "llcvt.c", "lib_a5f0"),
]
TOK = re.compile(r"[A-Za-z_]\w*|\d+|\S")


def strip(text):
    return re.sub(r"/\*.*?\*/|//[^\n]*", " ", text, flags=re.S)


def definitions(text):
    """[(name, tokens)] of top-level function definitions, in order."""
    text, out, i = strip(text), [], 0
    for m in re.finditer(r"^[A-Za-z][^\n;{}()#]*?\b(\w+)\s*\([^;{)]*\)\s*\{", text, re.M):
        if m.start() < i:
            continue
        depth, j = 0, m.end() - 1
        while True:
            depth += {"{": 1, "}": -1}.get(text[j], 0)
            j += 1
            if depth == 0:
                break
        out.append((m.group(1), TOK.findall(text[m.start():j])))
        i = j
    return out


def main():
    ultra = {f: dict(definitions((ULTRA / "src/libc" / f).read_text())) for f in ("ll.c", "llcvt.c")}
    order = {f: [n for n, _ in definitions((ULTRA / "src/libc" / f).read_text())] for f in ultra}
    rows, ok = [], True
    for tu in ("lib_e4f0", "lib_a5f0"):
        src = subprocess.run(["git", "show", f"{BASE}:src/rom/{tu}.c"], cwd=REPO, check=True,
                             capture_output=True, text=True).stdout
        defs = definitions(src)
        mine = [r for r in ROWS if r[4] == tu]
        names = [n for n, _ in defs]
        if names != [r[1] for r in mine]:
            print(f"{tu}: definition order {names} != table"); ok = False
        ufile = mine[0][3]
        if [r[2] for r in mine] != order[ufile]:
            print(f"{tu}: ultralib {ufile} order {order[ufile]} != table"); ok = False
        for (vram, old, new, uf, _), (name, toks) in zip(mine, defs):
            renamed = [new if t == old else t for t in toks]
            same = renamed == ultra[uf][new]
            ok &= same
            print(f"0x{vram:08X} {old:15s} -> {new:14s} {uf:8s} {'IDENTICAL tokens' if same else 'DIFFERENT'}")
            rows.append({"vram": f"0x{vram:08X}", "old": old, "new": new,
                         "ultralib": f"src/libc/{uf}", "confidence": "high",
                         "status": "accepted" if same else "rejected (body differs)",
                         "evidence": f"locked {old} in src/rom/{tu}.c (score 0, w16g) is the ultralib "
                                     f"{uf} definition of {new} token for token after the rename; "
                                     f"position {order[uf].index(new) + 1} of {len(order[uf])} in {uf}, "
                                     f"same as its ROM order in {tu}"})
    doc = {"note": "w23g: libgcc-named boot helpers -> ultralib VERSION_J ll.c/llcvt.c names. "
                   "Generated by cloud/work/frontier/w23g/ll_check.py (token comparison of the "
                   "locked src/rom definitions against reference/repos/ultralib).",
           "sdk": "ultralib (decompals/ultralib e24c836, reference/repos/ultralib); ll.c/llcvt.c "
                  "have no version branches",
           "renames": rows}
    (Path(__file__).parent / "ll_renames.json").write_text(json.dumps(doc, indent=1) + "\n")
    print("ALL ACCEPTED" if ok else "SOME REJECTED")
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
