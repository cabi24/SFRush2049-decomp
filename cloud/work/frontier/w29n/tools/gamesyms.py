#!/usr/bin/env python3
"""w29n: write the data renames of renames.json into disasm.GAME_SYMBOLS (generated block).

    python3 cloud/work/frontier/w29n/tools/gamesyms.py MAP.json

GAME_SYMBOLS is the hand table of game data names; the accepted `kind: data` rows
go into one block between BEGIN/END markers placed before `_LINE_RE` (replaced
if present), with each row's evidence as its comment and the deferred data rows
listed. A later GAME_SYMBOLS.update wins over earlier entries at one address.
"""
import json
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[5]
DISASM = REPO / "tools/conveyor/pipeline/disasm.py"
BEGIN = "# --- BEGIN w29n GAME_SYMBOLS (generated by cloud/work/frontier/w29n/tools/gamesyms.py) ---\n"
END = "# --- END w29n GAME_SYMBOLS ---\n"


def block(rows):
    acc = [r for r in rows if r.get("kind") == "data" and r.get("status", "accepted") == "accepted"]
    dfr = [r for r in rows if r.get("kind") == "data" and r.get("status") == "deferred"]
    out = [BEGIN,
           "# Names from the GameCube debug build (docs/external/gc/names.md; table\n",
           "# cloud/work/frontier/w29n/renames.json, evidence per row there).\n"]
    if dfr:
        out.append("# Deferred until their fixtures move: "
                   + ", ".join(f"{r['new']} {r['vram']}" for r in dfr) + ".\n")
    out.append("GAME_SYMBOLS.update({\n")
    for r in acc:
        ev = r["evidence"].split(";")[0].split(":")[0]
        out.append(f"    {r['vram']}: {json.dumps(r['new'])},  # {ev}\n")
    out += ["})\n", END, "\n"]
    return "".join(out)


def main():
    rows = json.loads(Path(sys.argv[1]).read_text())["renames"]
    text = DISASM.read_text()
    if BEGIN in text:
        a, b = text.index(BEGIN), text.index(END) + len(END) + 1
        text = text[:a] + text[b:]
