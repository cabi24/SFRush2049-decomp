#!/usr/bin/env python3
"""instrument71_uopt.py IN.c OUT.c -- globalcolor (CDX) trace + force oracle for the recompiled IDO 7.1 uopt.c.

Input: build/7.1/uopt.c generated by decompals/ido-static-recomp v1.2 (`recomp.elf ido/7.1/usr/lib/uopt`),
pinned by sha256 below. This is a port of the vendored workbench `instrument-uopt --profile globalcolor`
(IDO 5.3) to the 7.1 generated source: the 7.1 globalcolor is the same procedure (same frame slots
sp+212/216/220/268/272/276, same live-range offsets +28 nocs, +32 colour, +36 numintf, +40/+44 forbidden,
+48 save), only the labels and two globals moved:
    5.3 0x1001eb70 (allcallersave byte)      -> 7.1 0x1001c4d0
    5.3 0x10021c74 (current procedure)       -> 7.1 0x1001c530
and the 7.1 phase-one/phase-two callee-cost compares sit behind a delay-slot split, so those two cost hooks
are placed on the join label (L469c54 / L46a640) instead of on the compare.

Additions over the 5.3 profile (7.1 only):
  * procedure names. 7.1 uopt keeps the current procedure name at 0x1001eb00 (length word 0x1001c330; found
    from f_proc_suppressed, which compares the -Wo,-noopt list against it). At every globalcolor entry the
    pass prints `[CDX] procname proc=<ordinal> name=<name>` when CDX_LOG is set.
  * CDX_FN=<name>: restrict logging and CDX_FORCE to that procedure by name (no ordinal lookup needed;
    CDX_PROC=<ordinal> still works).
Every hook only reads emulated memory unless CDX_FORCE names a web, so with CDX_FORCE unset the output is
byte-identical to the stock pass (trace71 fidelity.sh checks it).
"""
import hashlib
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[6]   # repo root (cloud/work/frontier/tools/trace71/patches)
sys.path.insert(0, str(ROOT / 'third_party' / 'n64-decomp-workbench' / 'src'))
from decomp_workbench import instrument_uopt as wb  # noqa: E402

PIN = '0f2c66d2098e373fcc18d51a5220058f417ae6e91479f13f7b0b8d5291eadd01'
MARK = 'W22C_UOPT71_GLOBALCOLOR_V1'

NAME71 = r'''
/* W22C_UOPT71_GLOBALCOLOR_V1 -- 7.1 additions: procedure names, CDX_FN */
static char w71_fn[256];
static int w71_fn_ready;
static int w71_name(uint8_t *mem, char *buf, int size) {
    int n = (int)MEM_U32(0x1001c330), i;
    if (n < 0 || n >= size) n = size - 1;
    for (i = 0; i < n; i++) buf[i] = (char)MEM_S8(0x1001eb00 + i);
    buf[n] = 0;
    while (n > 0 && buf[n - 1] == ' ') buf[--n] = 0;
    return n;
}
static void w71_entry(uint8_t *mem, int ordinal) {
    char name[1100];
    if (!w71_fn_ready) {
        const char *v = getenv("CDX_FN");
        w71_fn_ready = 1;
        if (v && *v) strncpy(w71_fn, v, sizeof(w71_fn) - 1);
    }
    w71_name(mem, name, sizeof(name));
    if (w71_fn[0]) dkwb_cdx_proc = strcmp(name, w71_fn) == 0 ? ordinal : 0x7fffffff;
    if (dkwb_cdx_log && (!w71_fn[0] || dkwb_cdx_proc == ordinal))
        fprintf(dkwb_cdx_output, "[CDX] procname proc=%d name=%s\n", ordinal, name);
}
'''


def once(s, old, new, label):
    n = s.count(old)
    if n != 1:
        raise SystemExit('instrument71_uopt: anchor %r occurs %d times' % (label, n))
    return s.replace(old, new, 1)


def cost(phase, web_slot, kind):
    return ('DKWB_CDX_COST(dkwb_cdx_ordinal, "%s", (int)MEM_U32(sp + %d), (int)s2, "%s", f2.f[0], f20.f[0]);\n'
            % (phase, web_slot, kind))


def decision(phase, web_slot, save, nocs, tot, labels, force_true):
    # force_true: the value of cf that means "split" (p1) / "color" (p2)
    on, off = force_true
    return (
        "{\n"
        "    int dkwb_web = (int)MEM_U32(sp + %d);\n"
        "    dkwb_cdx_proc_decisions++;\n"
        "    dkwb_cdx_decision = dkwb_cdx_force_color(dkwb_cdx_ordinal, \"%s\", \"dec\", dkwb_web,\n"
        "        MEM_U32(s5 + 40), MEM_U32(s5 + 44));\n"
        "    DKWB_CDX_LOG(dkwb_cdx_ordinal, \"[CDX] %sdec phase=%s proc=%%d web=%%d sym=%%d class=%%d save=%%.6f "
        "nocs=%%d totalsave=%%.6f bestcost=%%.6f bestcolor=%%d bestreg=%%s forbidden0=0x%%08x forbidden1=0x%%08x "
        "regsleft=%%d numintf=%%d available0=0x%%08x available1=0x%%08x allcallersave=%%d taken1=%%d taken2=%%d "
        "decision=%%s forced=%%d\\n\", dkwb_cdx_ordinal, dkwb_web, (int)MEM_U16(MEM_U32(s5 + 0) + 2), (int)s6, "
        "(double)%s.f[0], (int)%s, (double)%s.f[0], (double)f20.f[0], (int)MEM_U32(sp + 220), "
        "dkwb_cdx_register_name((int)MEM_U32(sp + 220)), (unsigned int)MEM_U32(s5 + 40), "
        "(unsigned int)MEM_U32(s5 + 44), (int)MEM_U8(s5 + 33), (int)MEM_U32(s5 + 36), "
        "(unsigned int)MEM_U32(sp + 212), (unsigned int)MEM_U32(sp + 216), (int)MEM_U8(0x1001c4d0), "
        "dkwb_cdx_reg_taken(mem, 1), dkwb_cdx_reg_taken(mem, 2), cf ? \"%s\" : \"%s\", dkwb_cdx_decision);\n"
        "    dkwb_cdx_log_interference(mem, dkwb_cdx_ordinal, \"%s\", dkwb_web, s5);\n"
        "    if (dkwb_cdx_decision == -1) cf = %d;\n"
        "    else if (dkwb_cdx_decision >= 0) cf = %d;\n"
        "}\n" % (web_slot, phase, phase, phase, save, nocs, tot, labels[0], labels[1], phase, on, off))


def color(phase, web_slot, reg):
    return (
        "{\n"
        "    int dkwb_web = (int)MEM_U32(sp + %d);\n"
        "    int dkwb_force = dkwb_cdx_force_color(dkwb_cdx_ordinal, \"%s\", \"color\", dkwb_web,\n"
        "        MEM_U32(s5 + 40), MEM_U32(s5 + 44));\n"
        "    if (dkwb_force >= 0) {\n"
        "        MEM_U32(sp + 220) = (uint32_t)dkwb_force;\n"
        "        %s = (uint32_t)dkwb_force;\n"
        "    }\n"
        "    DKWB_CDX_LOG(dkwb_cdx_ordinal, \"[CDX] %scolor phase=%s proc=%%d web=%%d sym=%%d color=%%d reg=%%s "
        "forced=%%d\\n\", dkwb_cdx_ordinal, dkwb_web, (int)MEM_U16(MEM_U32(s5 + 0) + 2), (int)MEM_U32(sp + 220), "
        "dkwb_cdx_register_name((int)MEM_U32(sp + 220)), dkwb_force);\n"
        "}\n" % (web_slot, phase, reg, phase, phase))


def instrument(src):
    if MARK in src:
        raise SystemExit('instrument71_uopt: already instrumented')
    header = wb.HEADER.replace('DKWB_CDX_COLOR_TABLE\n', wb.color_register_table())
    header = header.replace('MEM_U32(0x10021c74)', 'MEM_U32(0x1001c530)')
    # CDX_FN selects the procedure by name, so a force needs no CDX_PROC
    header = once(header, '        if (dkwb_cdx_proc < 0) {\n            fprintf(stderr, "DKWB: CDX_FORCE ignored',
                  '        if (dkwb_cdx_proc < 0 && !getenv("CDX_FN")) {\n            fprintf(stderr, "DKWB: CDX_FORCE ignored',
                  'force without proc')
    assert '0x10021c74' not in header and '0x1001eb70' not in header
    s = once(src, 'static void f_compute_save(uint8_t *mem, uint32_t sp, uint32_t a0) {\n',
             header + NAME71 + '\nstatic void f_compute_save(uint8_t *mem, uint32_t sp, uint32_t a0) {\n', 'header')
    s = once(s, 'uint32_t a3 = 0;\nL469280:\n//globalcolor:',
             'uint32_t a3 = 0;\nint dkwb_cdx_ordinal;\nint dkwb_cdx_decision;\n'
             'dkwb_cdx_init();\ndkwb_cdx_procindex();\ndkwb_cdx_proc_decisions = 0;\n'
             'dkwb_cdx_globalcolor_ordinal++;\ndkwb_cdx_ordinal = dkwb_cdx_globalcolor_ordinal;\n'
             'w71_entry(mem, dkwb_cdx_ordinal);\n'
             'DKWB_CDX_LOG(dkwb_cdx_ordinal, "[CDX] globalcolor proc=%d\\n", dkwb_cdx_ordinal);\n'
             'L469280:\n//globalcolor:', 'globalcolor entry')
    s = once(s, 'L4698f4:\nf0.w[0] = MEM_U32(s5 + 48);\n',
             'L4698f4:\nf0.w[0] = MEM_U32(s5 + 48);\n'
             'DKWB_CDX_LOG(dkwb_cdx_ordinal, "[CDX] p1cand phase=p1 proc=%d web=%d sym=%d save=%.6f nocs=%d '
             'best=%.6f\\n", dkwb_cdx_ordinal, (int)MEM_U32(sp + 272), (int)MEM_U16(MEM_U32(s5 + 0) + 2), '
             '(double)f0.f[0], (int)MEM_U32(s5 + 28), (double)f20.f[0]);\n', 'phase-one candidate')
    s = once(s, 'L469a84:\ncf = f2.f[0] < f20.f[0];', 'L469a84:\n' + cost('p1', 268, 'caller')
             + 'cf = f2.f[0] < f20.f[0];', 'phase-one caller cost')
    s = once(s, 'L469c54:\n', 'L469c54:\n' + cost('p1', 268, 'callee'), 'phase-one callee cost')
    s = once(s, 'cf = f6.f[0] <= f20.f[0];\n//nop;\nif (!cf) {',
             'cf = f6.f[0] <= f20.f[0];\n' + decision('p1', 268, 'f10', 't2', 'f6', ('split', 'color'), (1, 0))
             + '//nop;\nif (!cf) {', 'phase-one decision')
    s = once(s, 'L469e84:\nt5 = MEM_U32(sp + 220);', 'L469e84:\n' + color('p1', 268, 't8')
             + 't5 = MEM_U32(sp + 220);', 'phase-one color')
    s = once(s, 'L46a450:\ncf = f2.f[0] < f20.f[0];', 'L46a450:\n' + cost('p2', 272, 'caller')
             + 'cf = f2.f[0] < f20.f[0];', 'phase-two caller cost')
    s = once(s, 'L46a640:\n', 'L46a640:\n' + cost('p2', 272, 'callee'), 'phase-two callee cost')
    s = once(s, 'cf = f20.f[0] < f10.f[0];\n//nop;\nif (!cf) {',
             'cf = f20.f[0] < f10.f[0];\n' + decision('p2', 272, 'f8', 't0', 'f10', ('color', 'no-color'), (0, 1))
             + '//nop;\nif (!cf) {', 'phase-two decision')
    s = once(s, 'L46a82c:\nt8 = MEM_U32(sp + 220);', 'L46a82c:\n' + color('p2', 272, 't0')
             + 't8 = MEM_U32(sp + 220);', 'phase-two color')
    return s


def main():
    src = open(sys.argv[1]).read()
    dig = hashlib.sha256(src.encode()).hexdigest()
    if dig != PIN and '--allow-unpinned' not in sys.argv:
        raise SystemExit('instrument71_uopt: %s is not the pinned 7.1 uopt.c (%s)' % (sys.argv[1], dig))
    open(sys.argv[2], 'w').write(instrument(src))
    print('instrument71_uopt ->', sys.argv[2])


if __name__ == '__main__':
    main()
